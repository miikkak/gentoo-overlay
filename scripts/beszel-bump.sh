#!/usr/bin/env bash
# Bump the beszel-agent and beszel-hub ebuilds to an upstream release.
#
#   - builds the deps/web distfiles (or reuses the overlay release if it exists,
#     so published hashes never change)
#   - uploads them to the overlay release "beszel-<ver>" (unless --no-upload)
#   - renames the ebuilds and regenerates both thin Manifests
#
# Usage: beszel-bump.sh [--no-upload] [version]
# Without a version, the latest upstream release is used. Prints "bumped=<ver>"
# on stdout when something changed, "bumped=" otherwise.
set -Eeuo pipefail
trap 'echo "Error on line $LINENO" >&2' ERR

dist=""
readonly OVERLAY_REPO="miikkak/gentoo-overlay"
readonly UPSTREAM_REPO="henrygd/beszel"
readonly UPSTREAM_URL="https://github.com/${UPSTREAM_REPO}"

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
readonly root
# shellcheck source=scripts/lib/overlay.sh
. "${root}/scripts/lib/overlay.sh"

current_version() {
  local f
  for f in "${root}"/net-analyzer/beszel-agent/beszel-agent-*.ebuild; do
    f="${f##*/beszel-agent-}"
    printf '%s\n' "${f%.ebuild}"
    return
  done
}

main() {
  local upload=true version=""
  while (($#)); do
    case "$1" in
      --no-upload) upload=false ;;
      -*)
        echo "Unknown option: $1" >&2
        exit 2
        ;;
      *) version="${1#v}" ;;
    esac
    shift
  done

  if [[ -z "${version}" ]]; then
    step "Querying latest upstream release"
    version="$(gh api "repos/${UPSTREAM_REPO}/releases/latest" --jq .tag_name)"
    version="${version#v}"
  fi
  require_version "${version}"

  local current
  current="$(current_version)"
  echo "current=${current} upstream=${version}" >&2
  if ! is_newer "${current}" "${version}"; then
    echo "Nothing to do: ${version} is not newer than ${current}" >&2
    echo "bumped="
    return
  fi

  dist="$(mktemp -d)"
  trap 'rm -rf "${dist}"' EXIT
  local tag="beszel-${version}"

  if gh release view "${tag}" --repo "${OVERLAY_REPO}" >/dev/null 2>&1; then
    step "Reusing distfiles from existing release ${tag}"
    gh release download "${tag}" --repo "${OVERLAY_REPO}" --dir "${dist}" \
      --pattern "beszel-${version}-*.tar.xz"
    local asset
    for asset in "beszel-${version}-deps.tar.xz" "beszel-${version}-web.tar.xz"; do
      [[ -s "${dist}/${asset}" ]] || {
        echo "Release ${tag} is missing ${asset}" >&2
        exit 1
      }
    done
  else
    "${root}/scripts/beszel-build-distfiles.sh" "${version}" "${dist}"
    if [[ "${upload}" == true ]]; then
      step "Publishing release ${tag}"
      gh release create "${tag}" --repo "${OVERLAY_REPO}" \
        --title "Beszel ${version} distfiles" \
        --notes "Offline build inputs for net-analyzer/beszel-{agent,hub}-${version} (go mod vendor tree, built web UI). Generated by scripts/beszel-build-distfiles.sh." \
        "${dist}/beszel-${version}-deps.tar.xz" "${dist}/beszel-${version}-web.tar.xz"
    fi
  fi

  step "Fetching upstream source archive"
  curl -fsSL --retry 3 -o "${dist}/beszel-${version}.tar.gz" \
    "${UPSTREAM_URL}/archive/refs/tags/v${version}.tar.gz"

  step "Updating ebuilds and Manifests"
  local pkg
  for pkg in beszel-agent beszel-hub; do
    git -C "${root}" mv \
      "net-analyzer/${pkg}/${pkg}-${current}.ebuild" "net-analyzer/${pkg}/${pkg}-${version}.ebuild"
  done
  write_manifest net-analyzer/beszel-agent "${dist}/beszel-${version}.tar.gz" "${dist}/beszel-${version}-deps.tar.xz"
  write_manifest net-analyzer/beszel-hub "${dist}/beszel-${version}.tar.gz" "${dist}/beszel-${version}-deps.tar.xz" \
    "${dist}/beszel-${version}-web.tar.xz"

  echo "bumped=${version}"
}

main "$@"
